// Builds the migration that loads the built-in food tables.
//
// Sources (download them first, see docs/alimentos.md):
//   TACO 4th ed. (NEPA/UNICAMP), processed CSV: taco_composicao.csv
//   CoFID 2021 (McCance and Widdowson, UK government): the .xlsx workbook
//
// Usage: node scripts/build-foods.mjs <taco_composicao.csv> <cofid.xlsx>
import { readFileSync, writeFileSync } from 'node:fs';
import readXlsxFile from 'read-excel-file/node';
import { cofidFood, foodsInsertSql, parseCsv, tacoFood, uniqueExternalIds } from './foods-map.mjs';

const [tacoPath, cofidPath] = process.argv.slice(2);
if (!tacoPath || !cofidPath) {
  console.error('Usage: node scripts/build-foods.mjs <taco_composicao.csv> <cofid.xlsx>');
  process.exit(1);
}

const [tacoHeader, ...tacoRows] = parseCsv(readFileSync(tacoPath, 'utf8'));
const taco = tacoRows
  .map((cells) => tacoFood(Object.fromEntries(tacoHeader.map((h, i) => [h, cells[i]]))))
  .filter(Boolean);

const sheets = await readXlsxFile(cofidPath);
const proximates = sheets.find((s) => s.sheet === '1.3 Proximates');
if (!proximates) throw new Error("CoFID workbook has no '1.3 Proximates' sheet");
const [cofidHeader, , , ...cofidRows] = proximates.data; // two rows of codes follow the header
const cofid = cofidRows
  .map((cells) => cofidFood(Object.fromEntries(cofidHeader.map((h, i) => [h, cells[i]]))))
  .filter(Boolean);

const out = 'supabase/migrations/20261118000003_foods_seed.sql';
writeFileSync(out,
  '-- Built-in foods. Generated by scripts/build-foods.mjs; do not edit by hand.\n' +
  `-- TACO 4th ed. (NEPA/UNICAMP, 2011): ${taco.length} foods. Reproduction allowed with credit to the source.\n` +
  `-- CoFID 2021 (McCance and Widdowson, Public Health England): ${cofid.length} foods. Open Government Licence v3.0.\n\n` +
  foodsInsertSql(uniqueExternalIds([...taco, ...cofid])));
console.log(`TACO ${taco.length}, CoFID ${cofid.length} -> ${out}`);
